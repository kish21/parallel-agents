def _subprocess_runner(root: Path) -> CommandRunner:
    def run(argv: Sequence[str]) -> CommandResult:
        res = subprocess.run(list(argv), cwd=str(root), capture_output=True, text=True,
                             encoding="utf-8", errors="replace")
        return CommandResult(res.returncode, res.stdout or "", res.stderr or "")
    return run


class BoardReader:
    """Reads Lane, Owner and Seat for every card, keyed by ticket number."""

    def __init__(self, settings, root: Path, gh: str = "gh",
                 runner: Optional[CommandRunner] = None):
        self.settings = settings
        self.root = Path(root)
        self.gh = gh
        self._run = runner or _subprocess_runner(self.root)

    def _call(self, argv: Sequence[str]) -> str:
        try:
            res = self._run(argv)
        except FileNotFoundError as exc:
            raise BoardError(
                f"The GitHub command line tool ('{self.gh}') is not installed, so I "
                f"cannot read the board.") from exc
        except OSError as exc:
            raise BoardError(f"Could not run '{' '.join(argv)}': {exc}") from exc
        if res.returncode != 0:
            detail = res.stderr.strip()
            hint = ""
            if "project" in detail.lower() and "scope" in detail.lower():
                hint = " Run: gh auth refresh -s project,read:project"
            raise BoardError(
                f"Reading the board failed: {detail or 'gh exited ' + str(res.returncode)}."
                + hint)
        return res.stdout

    def _owner_argv(self) -> List[str]:
        return ["--owner", self.settings.owner] if self.settings.owner else ["--owner", "@me"]

    def project_number(self) -> int:
        """The board with the configured title, by number. Absent is an error that says so."""
        out = self._call([self.gh, "project", "list", *self._owner_argv(),
                          "--format", "json", "--limit", "200"])
        try:
            data = json.loads(out or "{}")
        except ValueError as exc:
            raise BoardError(f"The board list from gh was not JSON: {exc}") from exc
        for project in data.get("projects", []) or []:
            if str(project.get("title", "")) == self.settings.title:
                return int(project["number"])
        raise BoardError(
            f"There is no board called '{self.settings.title}' for "
            f"{self.settings.owner or 'this account'}. Run 'lanekeeper board' to create "
            f"it, or set board.title to the board you use.")

    def cards(self) -> Dict[str, BoardCard]:
        number = self.project_number()
        out = self._call([self.gh, "project", "item-list", str(number),
                          *self._owner_argv(), "--format", "json", "--limit", "1000"])
        try:
            data = json.loads(out or "{}")
        except ValueError as exc:
            raise BoardError(f"The card list from gh was not JSON: {exc}") from exc
        return parse_items(data.get("items", []) or [])


def parse_items(items: Sequence[dict]) -> Dict[str, BoardCard]:
    """The cards out of `gh project item-list --format json`.

    gh writes each single-select field as a top-level key named after the field in
    lower case, next to the `content` block that names the issue. Both spellings of
    each field are read, because the field names are the user's and the board may be
    older than this code.
    """
    cards: Dict[str, BoardCard] = {}
    for item in items:
        content = item.get("content") or {}
        number = content.get("number")
        if number is None:
            continue
        ref = str(number)

        def field(name: str) -> str:
            for key in (name.lower(), name, name.capitalize()):
                value = item.get(key)
                if isinstance(value, str) and value.strip():
                    return value.strip()
            return ""

        cards[ref] = BoardCard(ref=ref, lane=field("lane"), owner=field("owner"),
                               seat=field("seat"), status=field("status"))
    return cards


def render_cards(cards: Dict[str, BoardCard]) -> str:
    if not cards:
        return "The board has no cards yet."
    lines = ["Ticket   Lane                 Owner     Seat   Status", "-" * 60]
    for ref in sorted(cards, key=lambda r: int(r) if r.isdigit() else 0):
        c = cards[ref]
        lines.append(f"#{ref:<7} {c.lane or '-':<20} {c.owner or '-':<9} "
                     f"{c.seat or '-':<6} {c.status or '-'}")
    blank = [r for r, c in cards.items() if not c.lane]
    if blank:
        lines += ["", f"{len(blank)} card(s) have no Lane: "
                  + ", ".join(f"#{r}" for r in sorted(blank)[:10])
                  + ". Set it on the board; a card with no lane belongs to nobody."]
    return "\n".join(lines)
